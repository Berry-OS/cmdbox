cases = cases1 + cases2
ref_env = dict(os.environ, HOME='/root', LC_ALL='C', ENV='')
failures = []
checks = 0

def run(argv, text, mode, d):
    if mode == 'c':
        return subprocess.run(argv + ['-c', text], capture_output=True, env=ref_env, timeout=10, input=b'', cwd=d)
    if mode == 'file':
        p = os.path.join(d, 'script.sh')
        open(p, 'w').write(text)
        return subprocess.run(argv + [p], capture_output=True, env=ref_env, timeout=10, input=b'', cwd=d)
    return subprocess.run(argv, capture_output=True, env=ref_env, timeout=10, input=text.encode(), cwd=d)

for c in cases:
    for mode in ('c', 'file', 'stdin'):
        checks += 1
        with tempfile.TemporaryDirectory() as d:
            r = run(['bash', '--posix'], c, mode, d)
        with tempfile.TemporaryDirectory() as d:
            try:
                b = run([binary, 'sh'], c, mode, d)
            except subprocess.TimeoutExpired:
                failures.append((mode, c, 'TIMEOUT'))
                continue
        if (r.stdout, r.returncode) != (b.stdout, b.returncode):
            failures.append((mode, c, (r.returncode, r.stdout[:120]), (b.returncode, b.stdout[:120], b.stderr[:100])))
if failures:
    for f in failures[:20]:
        print('FAIL', f)
    sys.exit(1)
print(f'{checks} shell conformance checks passed')
